import assert from "node:assert/strict"
import test from "node:test"
import { buildFeed, parseManifest, type DocumentCandidate } from "./index"

const documents: DocumentCandidate[] = [
  {
    relativePath: "研究/空间 结构.md",
    slug: "研究/空间-结构",
    aliases: ["精选/动态空间"],
    frontmatter: { permalink: "精选/动态空间" },
  },
  {
    relativePath: "项目/研究工具.md",
    slug: "项目/研究工具",
    aliases: [],
    frontmatter: {},
  },
]

test("parses, resolves, sorts and omits disabled entries", () => {
  const entries = parseManifest(`---
homepageManifest: 1
---

## [[项目/研究工具|研究工具]]
bind:: projects
appearance:: browser
summary:: 用于管理研究资料的工具页面。
cover:: [[附件/research tool.png]]
tags:: 工具，项目
order:: 20

## [[研究/空间 结构|漫画纸面中的动态空间结构]]
bind:: research
appearance:: text
summary:: 关于漫画分镜与空间运动关系的研究笔记。
tags:: 漫画, 空间
order:: 10
enabled:: true

## [[项目/研究工具|不显示]]
bind:: projects
appearance:: text
summary:: 已停用。
order:: 1
enabled:: false
`)
  const feed = buildFeed(
    entries,
    documents,
    ["研究/空间 结构.md", "项目/研究工具.md", "附件/research tool.png"],
    "willkyu.github.io/research",
    "2026-11-05T00:00:00.000Z",
  )

  assert.deepEqual(feed, {
    schemaVersion: 1,
    source: "research",
    generatedAt: "2026-11-05T00:00:00.000Z",
    items: [
      {
        bind: "research",
        title: "漫画纸面中的动态空间结构",
        summary: "关于漫画分镜与空间运动关系的研究笔记。",
        href: "/research/%E7%B2%BE%E9%80%89/%E5%8A%A8%E6%80%81%E7%A9%BA%E9%97%B4",
        appearance: "text",
        tags: ["漫画", "空间"],
        order: 10,
      },
      {
        bind: "projects",
        title: "研究工具",
        summary: "用于管理研究资料的工具页面。",
        href: "/research/%E9%A1%B9%E7%9B%AE/%E7%A0%94%E7%A9%B6%E5%B7%A5%E5%85%B7",
        appearance: "browser",
        tags: ["工具", "项目"],
        order: 20,
        cover: "/research/%E9%99%84%E4%BB%B6/research-tool.png",
      },
    ],
  })
})

test("rejects hand-written ids and missing covers", () => {
  assert.throws(
    () =>
      parseManifest(`---
homepageManifest: 1
---
## [[项目/研究工具|研究工具]]
bind:: projects
appearance:: browser
summary:: 工具。
order:: 1
id:: manual
`),
    /id is generated by the consumer and must not be set/,
  )
  assert.throws(
    () =>
      parseManifest(`---
homepageManifest: 1
---
## [[项目/研究工具|研究工具]]
bind:: projects
appearance:: gallery
summary:: 工具。
order:: 1
`),
    /appearance "gallery" requires cover/,
  )
})

test("rejects ambiguous links and duplicate resolved hrefs", () => {
  const ambiguous = parseManifest(`---
homepageManifest: 1
---
## [[主题|主题]]
bind:: research
appearance:: text
summary:: 主题。
order:: 1
`)
  assert.throws(
    () =>
      buildFeed(
        ambiguous,
        [
          { relativePath: "甲/主题.md", slug: "甲/主题", aliases: [], frontmatter: {} },
          { relativePath: "乙/主题.md", slug: "乙/主题", aliases: [], frontmatter: {} },
        ],
        ["甲/主题.md", "乙/主题.md"],
        "willkyu.github.io/research",
      ),
    /ambiguous document Wiki Link/,
  )

  const duplicate = parseManifest(`---
homepageManifest: 1
---
## [[研究/空间 结构|甲]]
bind:: research
appearance:: text
summary:: 甲。
order:: 1
## [[精选/动态空间|乙]]
bind:: research
appearance:: text
summary:: 乙。
order:: 2
`)
  assert.throws(
    () =>
      buildFeed(
        duplicate,
        documents,
        ["研究/空间 结构.md", "项目/研究工具.md"],
        "willkyu.github.io/research",
      ),
    /duplicate href/,
  )
})
